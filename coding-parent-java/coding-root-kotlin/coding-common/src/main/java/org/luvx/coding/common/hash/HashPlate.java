    public static DoubleSupplier splitMix32(int seed) {
        final int[] s = {seed};
        return () -> {
            s[0] += 0x9e3779b9;
            int z = s[0];
            z = (z ^ (z >>> 16)) * 0x21f0aaad;
            z = (z ^ (z >>> 15)) * 0x735a2d97;
            z ^= z >> 15;
            return (double) (z) / 4294967296L;
        };
    }

    public static String hashPlate(String val, Options opts) {
        int seed = opts.seed == 0 ? Arrays.hashCode(val.toCharArray()) : opts.seed;
        DoubleSupplier random = splitMix32(seed);
        IntUnaryOperator index = l -> (int) (random.getAsDouble() * l);
        ToCharFunction<String> randomStr = s -> s.charAt(index.applyAsInt(s.length()));
        Supplier<String> randomEmoji = () -> emojiDict[index.applyAsInt(emojiDict.length)];

        var alphabet = opts.excludeIO ? AlphabetNoOI : Alphabet;
        var alphanum = opts.excludeIO ? AlphanumNoOI : Alphanum;

        StringBuilder sb = new StringBuilder();
        if (opts.emoji) {
            sb.append(randomEmoji.get()).append(' ');
        }
        if (opts.cn) {
            char c = province[index.applyAsInt(province.length)];
            sb.append(c).append(randomStr.applyAsChar(alphabet)).append("·");
        }
        var n = opts.cn ? 5 : 7;
        for (int i = 0; i < n; i++) {
            if (opts.cn) {
                sb.append(randomStr.applyAsChar(alphanum));
                continue;
            }
            if (i <= 1) {
                sb.append(randomStr.applyAsChar(alphabet));
                if (i == 1) {
                    sb.append('-');
                }
            } else if (i < 5) {
                sb.append('0' + index.applyAsInt(10));
                if (i == 4) {
                    sb.append('-');
                }
            } else {
                sb.append(randomStr.applyAsChar(alphabet));
            }
        }

        if (opts.emoji) {
            sb.append(' ').append(randomEmoji.get());
        }
        return sb.toString();
    }

